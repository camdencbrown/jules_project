# The print() function displays text on the screen.
print("Hello, World! What's your name?")

# The input() function waits for the user to type something and press Enter.
# The text the user types is then stored in a variable called 'user_name'.
user_name = input()

# Now we print a new message that includes the user's name.
# We use an "f-string" (the f before the quotes) to easily insert the variable's value.
print(f"Nice to meet you, {user_name}!")

